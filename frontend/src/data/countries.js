// Default fallback country
const DEFAULT_COUNTRY = { name: "United States", code: "US", currency: "US Dollar", currencyCode: "USD", symbol: "$" };

export function findCountry(countryOrCode) {
  if (!countryOrCode) return DEFAULT_COUNTRY;
  const lower = String(countryOrCode).trim().toLowerCase();
  return (
    COUNTRIES.find(
      (c) => c.name.toLowerCase() === lower || c.code.toLowerCase() === lower
    ) ||
    COUNTRIES.find(
      (c) => c.name.toLowerCase().includes(lower) || lower.includes(c.name.toLowerCase())
    ) || {
      ...DEFAULT_COUNTRY,
      name: countryOrCode,
    }
  );
}

export function formatSalaryCurrency(amount, countryOrCode = "US") {
  const country = findCountry(countryOrCode);
  const symbol = country?.symbol || "$";
  if (typeof amount === "number") {
    return `${symbol}${amount.toLocaleString()}`;
  }
  if (!amount) return `${symbol}0`;
  const cleanNum = parseInt(String(amount).replace(/[^0-9]/g, ""), 10);
  if (isNaN(cleanNum)) return `${symbol}${amount}`;
  return `${symbol}${cleanNum.toLocaleString()}`;
}

